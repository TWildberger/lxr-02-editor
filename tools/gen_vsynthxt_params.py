#!/usr/bin/env python3
"""Expand the reviewed native XT schema into C++ (no PDF/runtime dependencies)."""
import argparse
import json
from pathlib import Path


def generate(root):
    schema = json.loads((root / "docs/vsynthxt/native-params.json").read_text())
    rows = []
    for group in schema["groups"]:
        for zone in range(group["zones"]):
            for section in group["sections"]:
                count = section.get("count", 1)
                for instance in range(count):
                    section_name = section["label"]
                    if count > 1 and not section.get("section_single"):
                        section_name += f" {instance + 1}"
                        if "instance_labels" in section:
                            section_name += " - " + section["instance_labels"][instance]
                    for key, label, offset, width, minimum, maximum, bias in section["params"]:
                        if section.get("section_single"):
                            label += f" {instance + 1}"
                        prefix = f"xt.native.{group['group'].lower()}"
                        if group["zones"] > 1:
                            prefix += f".zone{zone + 1}"
                        prefix += f".{section['key']}"
                        if count > 1:
                            prefix += f"{instance + 1}"
                        address = (group["base"] + zone * group["zone_stride"] + section["base"]
                                   + instance * section.get("stride", 0) + offset)
                        page = section.get("page", group["page"])
                        relative = section["base"] + instance * section.get("stride", 0) + offset
                        if group["group"] == "Oscillator" and relative >= 40:
                            page = 13
                        if group["group"] == "Envelope" and relative >= 60:
                            page = 14
                        if group["group"] == "LFO" and relative >= 30:
                            page = 15
                        rows.append([prefix + "." + key, label, group["group"], section_name,
                                     zone + 1 if group["zones"] > 1 else 0, address,
                                     width, minimum, maximum, bias, page])
    assert len({r[0] for r in rows}) == len(rows), "Duplicate parameter IDs"
    occupied = set()
    for row in rows:
        for address in range(row[5], row[5] + row[6]):
            assert address not in occupied, f"Overlapping parameter {row[0]}"
            occupied.add(address)
        assert row[6] in (1, 2, 4) and row[7] <= row[8]
    lines = ["// Generated by tools/gen_vsynthxt_params.py; edit native-params.json instead.",
             "static const std::vector<Parameter> nativeParameters {"]
    for row in rows:
        lines.append("    {" + ", ".join(json.dumps(v, ensure_ascii=True) for v in row) + "},")
    lines.extend(["};", ""])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    path = root / "devices/vsynthxt/NativeParams.gen.inc"
    content = generate(root)
    if args.check:
        if not path.exists() or path.read_text() != content:
            parser.exit(1, "XT generated parameter table is stale\n")
    else:
        path.write_text(content)


if __name__ == "__main__":
    main()
